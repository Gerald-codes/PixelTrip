/** Resolve a colour-key char to a CSS colour, or null when transparent/unknown. */
export function resolveSpriteColor(key: string): string | null {
  if (key === ".") return null;
  return SPRITE_COLORS[key] ?? null;
}

export function spriteGridFor(assetKey: string): SpriteGrid | null {
  return SPRITE_GRIDS[assetKey] ?? null;
}
